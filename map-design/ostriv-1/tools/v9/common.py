def png_bytes(img):
    H, W, _ = img.shape; raw = b''.join(b'\x00' + img[r].tobytes() for r in range(H))
    ch = lambda t, x: struct.pack('>I', len(x)) + t + x + struct.pack('>I', zlib.crc32(t + x) & 0xffffffff)
    return b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0)) + ch(b'IDAT', zlib.compress(raw, 6)) + ch(b'IEND', b'')
def b64file(p): return base64.b64encode(open(p, 'rb').read()).decode()
def b64img(img): return base64.b64encode(png_bytes(img)).decode()
class SVG:
    def __init__(s): s.o = []
    def a(s, t): s.o.append(t)
    def txt(s, x, y, t, sz=12, col='#111', anc='start', w='normal', halo=True):
        st = 'stroke="#fff" stroke-width="3.2" paint-order="stroke"' if halo else ''
        s.a(f'<text x="{x:.1f}" y="{y:.1f}" font-size="{sz}" fill="{col}" text-anchor="{anc}" font-weight="{w}" {st}>{t}</text>')
    def poly(s, pts, closed=True, **kw):
        p = ' '.join(f'{x:.1f},{y:.1f}' for x, y in pts); tag = 'polygon' if closed else 'polyline'
        extra = '' if closed else ' fill="none"'
        s.a(f'<{tag} points="{p}"{extra} ' + ' '.join(f'{k.replace("_", "-")}="{v}"' for k, v in kw.items()) + '/>')
    def html(s, w, h, path):
        open(path, 'w', encoding='utf-8').write(f'<html><head><meta charset="utf-8"></head><body style="margin:0"><svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" font-family="Segoe UI, Arial"><rect width="100%" height="100%" fill="#fff"/>' + ''.join(s.o) + '</svg></body></html>')
